#!/usr/bin/env python3
"""Export a tiny deterministic ONNX model with dynamic batch dimension.

Model: y = sum(x, dims=(2,3)) @ W + b  with fixed W,b (seeded).
Input:  float32 [N, 3, 8, 8]
Output: float32 [N, 4]

Provenance: generated by this script; not a trained accuracy claim.
License of this script/model artifact: project license (MIT intended).
"""
from __future__ import annotations

import json
import hashlib
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "models"
MODEL_PATH = OUT_DIR / "tiny_deterministic.onnx"
META_PATH = OUT_DIR / "tiny_deterministic.json"
FIXTURE_PATH = OUT_DIR / "tiny_deterministic_fixtures.npz"


def build_and_export() -> None:
    import onnx
    from onnx import TensorProto, helper, numpy_helper

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(0)
    W = rng.standard_normal((3 * 8 * 8, 4), dtype=np.float32) * 0.1
    b = rng.standard_normal((4,), dtype=np.float32) * 0.01

    # Graph: Flatten spatial+channel then Gemm.
    # Input X [N,3,8,8] -> Reshape [N, 192] -> Gemm -> Y [N,4]
    X = helper.make_tensor_value_info("input", TensorProto.FLOAT, ["N", 3, 8, 8])
    Y = helper.make_tensor_value_info("output", TensorProto.FLOAT, ["N", 4])
    W_init = numpy_helper.from_array(W, name="W")
    B_init = numpy_helper.from_array(b, name="B")
    shape = numpy_helper.from_array(np.array([0, 192], dtype=np.int64), name="shape_192")

    nodes = [
        helper.make_node("Reshape", ["input", "shape_192"], ["flat"]),
        helper.make_node("Gemm", ["flat", "W", "B"], ["output"], alpha=1.0, beta=1.0, transB=0),
    ]
    graph = helper.make_graph(nodes, "tiny_deterministic", [X], [Y], [W_init, B_init, shape])
    model = helper.make_model(graph, opset_imports=[helper.make_opsetid("", 13)])
    model.ir_version = 8
    onnx.checker.check_model(model)
    onnx.save(model, MODEL_PATH)

    # Reference outputs via onnxruntime
    import onnxruntime as ort

    sess = ort.InferenceSession(str(MODEL_PATH), providers=["CPUExecutionProvider"])
    fixtures = {}
    for batch in (1, 2, 4):
        x = rng.standard_normal((batch, 3, 8, 8), dtype=np.float32)
        y = sess.run(["output"], {"input": x})[0]
        fixtures[f"x_b{batch}"] = x
        fixtures[f"y_b{batch}"] = y
    np.savez_compressed(FIXTURE_PATH, **fixtures)

    # Compact binary blob for C++ parity tests (batch=1).
    blob_path = OUT_DIR / "tiny_b1_io.bin"
    x1 = fixtures["x_b1"].reshape(-1)
    y1 = fixtures["y_b1"].reshape(-1)
    with blob_path.open("wb") as f:
        f.write(b"BFIO")
        f.write(np.int32(1).tobytes())
        f.write(np.int32(x1.size).tobytes())
        f.write(np.int32(y1.size).tobytes())
        f.write(x1.astype(np.float32).tobytes())
        f.write(y1.astype(np.float32).tobytes())

    raw = MODEL_PATH.read_bytes()
    meta = {
        "name": "tiny_deterministic",
        "version": "1.0.0",
        "path": str(MODEL_PATH.relative_to(ROOT)).replace("\\", "/"),
        "source": "scripts/export_tiny_model.py (seeded weights, not trained)",
        "license": "Generated artifact for BatchFlow; redistribute with repository",
        "input": {"name": "input", "dtype": "float32", "shape": ["N", 3, 8, 8]},
        "output": {"name": "output", "dtype": "float32", "shape": ["N", 4]},
        "batch_dimension": 0,
        "preprocessing": "none — raw float32 tensor",
        "sha256": hashlib.sha256(raw).hexdigest(),
        "bytes": len(raw),
        "fixture": str(FIXTURE_PATH.relative_to(ROOT)).replace("\\", "/"),
        "cpp_blob": str(blob_path.relative_to(ROOT)).replace("\\", "/"),
        "tolerance": {"rtol": 1e-5, "atol": 1e-6},
        "accuracy_claim": "none — infrastructure smoke model only",
        "onnxruntime_python": "1.32.0",
        "onnxruntime_cpp": "Microsoft.ML.OnnxRuntime 1.32.0 (NuGet, CPU)",
    }
    META_PATH.write_text(json.dumps(meta, indent=2), encoding="utf-8")
    print(f"wrote {MODEL_PATH} sha256={meta['sha256']}")
    print(f"wrote {META_PATH}")
    print(f"wrote {FIXTURE_PATH}")
    print(f"wrote {blob_path}")


def verify_fixtures() -> None:
    import onnxruntime as ort

    meta = json.loads(META_PATH.read_text(encoding="utf-8"))
    data = np.load(FIXTURE_PATH)
    sess = ort.InferenceSession(str(MODEL_PATH), providers=["CPUExecutionProvider"])
    for batch in (1, 2, 4):
        x = data[f"x_b{batch}"]
        y_ref = data[f"y_b{batch}"]
        y = sess.run(["output"], {"input": x})[0]
        if not np.allclose(y, y_ref, rtol=meta["tolerance"]["rtol"], atol=meta["tolerance"]["atol"]):
            raise SystemExit(f"FIXTURE MISMATCH batch={batch}")
        # Batched vs unbatched equivalence for batch>1
        if batch > 1:
            parts = [sess.run(["output"], {"input": x[i : i + 1]})[0] for i in range(batch)]
            y_cat = np.concatenate(parts, axis=0)
            if not np.allclose(y, y_cat, rtol=meta["tolerance"]["rtol"], atol=meta["tolerance"]["atol"]):
                raise SystemExit(f"BATCH PARITY FAIL batch={batch}")
    print("VERIFY_OK fixtures and batch parity")


if __name__ == "__main__":
    build_and_export()
    verify_fixtures()
